export function reportStrings(r: Report) {
  return T[r.language] ?? T['pt-PT']
}

const CITE_RE = /\[([A-Za-z0-9._-]+)\]/g

function reportBodyText(r: Report): string {
  return [r.clinicalIndication, r.technique, r.comparison, ...r.findingsByRegion.map((f) => f.text), ...r.impression, ...r.recommendations, r.limitations].join(' ')
}

/** Evidence ids actually cited in the report text, in order of first appearance (then citations[]). */
export function citedEvidence(r: Report, evidence: EvidenceItem[]): EvidenceItem[] {
  const ids: string[] = []
  for (const m of reportBodyText(r).matchAll(CITE_RE)) if (!ids.includes(m[1])) ids.push(m[1])
  for (const c of r.citations) if (!ids.includes(c.evidenceId)) ids.push(c.evidenceId)
  return ids.map((id) => evidence.find((e) => e.id === id)).filter((e): e is EvidenceItem => !!e)
}

/** Vancouver-style numbering: evidence id → citation number in order of first citation. */
export function citationNumbers(r: Report, evidence: EvidenceItem[]): Map<string, number> {
  const map = new Map<string, number>()
  citedEvidence(r, evidence).forEach((e, i) => map.set(e.id, i + 1))
  return map
}

/** Replaces [evidenceId] markers by [n]; unknown markers (e.g. [F1]) are kept as written. */
export function numberCitations(text: string, numbers: Map<string, number>): string {
  return text.replace(CITE_RE, (all, id: string) => (numbers.has(id) ? `[${numbers.get(id)}]` : all))
}

export function studyLine(c: Case, lang: Report['language'] = 'pt-PT'): string {
  const regions = lang === 'en' ? REGION_LABEL_EN : REGION_LABEL
  const parts = c.series
    .map((s) => {
      const known = s.laterality && s.laterality !== 'unknown' && s.laterality !== 'none'
      if (lang === 'en') return `${s.modality} ${regions[s.region].toLowerCase()}${known ? ` (${s.laterality})` : ''}`
      const lat = known ? ` · ${s.laterality === 'bilateral' ? 'bilateral' : `lado ${LATERALITY_LABEL[s.laterality!].toLowerCase()}`}` : ''
      return `${MODALITY_LABEL[s.modality]} · ${regions[s.region].toLowerCase()}${lat}`
    })
    .filter((v, i, a) => a.indexOf(v) === i)
  return parts.join('; ')
}

/** Auto-generated, non-editable AI-use statement (spec §7.4). */
export function buildAiDeclaration(c: Case, r: Report): string {
  const en = r.language === 'en'
  const ai = reviewableFindings(c).filter((f) => f.origin === 'ai')
  const count = (s: string) => ai.filter((f) => f.status === s).length
  const clinician = (c.analysis?.findings ?? []).filter((f) => f.origin === 'clinician').length
  const kb = (c.analysis?.evidence ?? []).filter((e) => e.source === 'kb').length
  const nlm = c.analysis?.notebookLm.length ?? 0
  const sources: string[] = []
  if (kb) sources.push(en ? `curated evidence base (${kb} references)` : `base curada (${kb} ${kb === 1 ? 'referência' : 'referências'})`)
  if (nlm) sources.push(en ? `NotebookLM (${nlm} answers)` : `NotebookLM (${nlm} ${nlm === 1 ? 'resposta' : 'respostas'})`)
  const model = c.analysis ? `${c.analysis.model}` : r.generatedBy
  const pending = count('pending')
  if (en) {
    return [
      `This report was drafted with artificial intelligence assistance (${model}, ${formatDate(r.generatedAt)}).`,
      `AI-suggested findings: ${ai.length}; accepted: ${count('accepted')}; edited: ${count('edited')}; rejected: ${count('rejected')}${pending ? `; pending: ${pending}` : ''}; added by the clinician: ${clinician}.`,
      `Evidence: ${sources.length ? sources.join(' and ') : 'not consulted'}.`,
      r.status === 'validated' ? `Validated by ${r.validatedBy} on ${formatDateTime(r.validatedAt)}.` : 'Not yet validated by a physician.',
      'Research prototype — not a medical device.',
    ].join(' ')
  }
  return [
    `Este relatório foi redigido com assistência de inteligência artificial (${model}, ${formatDate(r.generatedAt)}).`,
    `Achados sugeridos pela IA: ${ai.length}; aceites: ${count('accepted')}; editados: ${count('edited')}; rejeitados: ${count('rejected')}${pending ? `; pendentes: ${pending}` : ''}; adicionados pelo clínico: ${clinician}.`,
    `Evidência: ${sources.length ? sources.join(' e ') : 'não consultada'}.`,
    r.status === 'validated' ? `Validado por ${r.validatedBy} em ${formatDateTime(r.validatedAt)}.` : 'Ainda não validado por um médico.',
    'Protótipo de investigação — não é um dispositivo médico.',
  ].join(' ')
}

/** The declaration frozen at validation time, or a live one for drafts. */
export function aiDeclarationFor(c: Case, r: Report): string {
  return r.status === 'validated' && r.aiDeclaration ? r.aiDeclaration : buildAiDeclaration(c, r)
}

/** «não verificada» / «texto de IA, não verificado» for references without a verified PMID/DOI. */
export function verificationNote(e: EvidenceItem, r: Report): string | undefined {
  const t = reportStrings(r)
  const k = evidenceVerification(e).kind
  return k === 'unverified' ? t.unverified : k === 'notebook' ? t.aiAnswer : undefined
}

function referenceLine(e: EvidenceItem, n: number, r: Report): string {
  const note = verificationNote(e, r)
  const ids = [e.doi ? `doi:${e.doi}` : '', e.pmid ? `PMID ${e.pmid}` : ''].filter(Boolean).join(' · ')
  const src = e.source === 'notebooklm' ? ' [NotebookLM]' : ''
  return `[${n}] ${e.citation}${ids ? ` ${ids}` : ''}${src}${note ? ` (${note})` : ''}`
}

function validationLines(r: Report): string[] {
  const t = reportStrings(r)
  if (r.status !== 'validated') return [t.notValidated]
  return [
    `${t.validated}: ${r.validatedBy}${r.validatorLicence ? ` (${t.licence} ${r.validatorLicence})` : ''} · ${formatDateTime(r.validatedAt)}`,
    r.contentHash ? `SHA-256: ${r.contentHash}` : '',
    t.localValidation,
  ].filter(Boolean)
}

/** Plain text with numbered sections, ready to paste into a RIS. */
export function reportToText(c: Case, r: Report, evidence: EvidenceItem[]): string {
  const t = reportStrings(r)
  const nums = citationNumbers(r, evidence)
  const cite = (s: string) => numberCitations(s, nums)
  const lines: string[] = []
  if (r.status !== 'validated') lines.push(`*** ${t.draft} ***`, '')
  lines.push(t.title.toUpperCase())
  lines.push(`${c.pseudoId} · ${studyLine(c, r.language)}`)
  lines.push(`${t.uploadDate}: ${formatDate(c.createdAt)} · ${t.reportDate}: ${formatDate(r.generatedAt)}`)
  lines.push('')
  let n = 1
  const section = (title: string) => lines.push(`${n++}. ${title.toUpperCase()}`)
  section(t.indication)
  lines.push(cite(r.clinicalIndication || '—'), '')
  section(t.technique)
  lines.push(cite(r.technique || '—'), '')
  section(t.comparison)
  lines.push(cite(r.comparison || '—'), '')
  section(t.findings)
  for (const f of r.findingsByRegion) lines.push(`${f.heading}: ${cite(f.text)}`)
  lines.push('')
  section(t.impression)
  r.impression.forEach((x, i) => lines.push(`${i + 1}. ${cite(x)}`))
  lines.push('')
  if (r.recommendations.length) {
    section(t.recommendations)
    r.recommendations.forEach((x) => lines.push(`- ${cite(x)}`))
    lines.push('')
  }
  if (r.limitations) {
    section(t.limitations)
    lines.push(cite(r.limitations), '')
  }
  const refs = citedEvidence(r, evidence)
  if (refs.length) {
    section(t.references)
    refs.forEach((e, i) => lines.push(referenceLine(e, i + 1, r)))
    lines.push('')
  }
  section(t.aiDeclaration)
  lines.push(aiDeclarationFor(c, r), '')
  section(t.validation)
  lines.push(...validationLines(r), '')
  lines.push(`${t.generated}: ${r.generatedBy} · ${formatDateTime(r.generatedAt)}`)
  lines.push(t.disclaimer)
  return lines.join('\n')
}

export function reportToMarkdown(c: Case, r: Report, evidence: EvidenceItem[]): string {
  const t = reportStrings(r)
  const nums = citationNumbers(r, evidence)
  const cite = (s: string) => numberCitations(s, nums)
  const out: string[] = []
  out.push(`# ${t.title}`, '')
  out.push(`**${c.pseudoId}** · ${studyLine(c, r.language)}  `)
  out.push(`${t.uploadDate}: ${formatDate(c.createdAt)} · ${t.reportDate}: ${formatDate(r.generatedAt)}`, '')
  if (r.status !== 'validated') out.push(`> **${t.draft}**`, '')
  out.push(`## ${t.indication}`, '', cite(r.clinicalIndication || '—'), '')
  out.push(`## ${t.technique}`, '', cite(r.technique || '—'), '')
  out.push(`## ${t.comparison}`, '', cite(r.comparison || '—'), '')
  out.push(`## ${t.findings}`, '')
  for (const f of r.findingsByRegion) out.push(`- **${f.heading}.** ${cite(f.text)}`)
  out.push('', `## ${t.impression}`, '')
  r.impression.forEach((x, i) => out.push(`${i + 1}. ${cite(x)}`))
  if (r.recommendations.length) {
    out.push('', `## ${t.recommendations}`, '')
    r.recommendations.forEach((x) => out.push(`- ${cite(x)}`))
  }
  if (r.limitations) out.push('', `## ${t.limitations}`, '', cite(r.limitations))
  const refs = citedEvidence(r, evidence)
  if (refs.length) {
    out.push('', `## ${t.references}`, '')
    refs.forEach((e, i) => {
      const link = e.doi ? ` [doi:${e.doi}](https://doi.org/${e.doi})` : e.url ? ` <${e.url}>` : ''
      const pm = e.pmid ? ` [PMID ${e.pmid}](https://pubmed.ncbi.nlm.nih.gov/${e.pmid}/)` : ''
      const note = verificationNote(e, r)
      const unv = note ? ` _(${note})_` : ''
      out.push(`${i + 1}. ${e.citation}${link}${pm}${e.source === 'notebooklm' ? ' — NotebookLM' : ''}${unv}`)
    })
  }
  out.push('', `## ${t.aiDeclaration}`, '', aiDeclarationFor(c, r))
  out.push('', `## ${t.validation}`, '')
  for (const l of validationLines(r)) out.push(`${l}  `)
  out.push('', '---', '', `_${t.disclaimer}_`, '')
  return out.join('\n')
}

