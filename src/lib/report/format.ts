export function reportStrings(r: Report) {
  return T[r.language]
}

/** Evidence ids actually cited in the report text, in order of first appearance. */
export function citedEvidence(r: Report, evidence: EvidenceItem[]): EvidenceItem[] {
  const text = [r.technique, ...r.findingsByRegion.map((f) => f.text), ...r.impression, ...r.recommendations, r.limitations].join(' ')
  const ids: string[] = []
  for (const m of text.matchAll(/\[([A-Za-z0-9._-]+)\]/g)) if (!ids.includes(m[1])) ids.push(m[1])
  for (const c of r.citations) if (!ids.includes(c.evidenceId)) ids.push(c.evidenceId)
  return ids.map((id) => evidence.find((e) => e.id === id)).filter((e): e is EvidenceItem => !!e)
}

export function reportToText(c: Case, r: Report, evidence: EvidenceItem[]): string {
  const t = T[r.language]
  const lines: string[] = []
  lines.push(t.title.toUpperCase())
  lines.push(`${c.pseudoId} · ${c.series.map((s) => `${MODALITY_LABEL[s.modality]} ${REGION_LABEL[s.region]}`).join(', ')}`)
  if (r.status !== 'validated') lines.push(t.draft)
  lines.push('')
  lines.push(`${t.indication}: ${r.clinicalIndication || '—'}`)
  lines.push(`${t.technique}: ${r.technique}`)
  lines.push(`${t.comparison}: ${r.comparison || '—'}`)
  lines.push('')
  lines.push(`${t.findings}:`)
  for (const f of r.findingsByRegion) lines.push(`${f.heading}: ${f.text}`)
  lines.push('')
  lines.push(`${t.impression}:`)
  r.impression.forEach((x, i) => lines.push(`${i + 1}. ${x}`))
  if (r.recommendations.length) {
    lines.push('')
    lines.push(`${t.recommendations}:`)
    r.recommendations.forEach((x) => lines.push(`- ${x}`))
  }
  if (r.limitations) {
    lines.push('')
    lines.push(`${t.limitations}: ${r.limitations}`)
  }
  const refs = citedEvidence(r, evidence)
  if (refs.length) {
    lines.push('')
    lines.push(`${t.references}:`)
    for (const e of refs) lines.push(`[${e.id}] ${e.citation}${e.doi ? ` doi:${e.doi}` : ''}`)
  }
  lines.push('')
  lines.push(`${t.generated}: ${r.generatedBy} · ${formatDateTime(r.generatedAt)}`)
  if (r.status === 'validated') lines.push(`${t.validated}: ${r.validatedBy} · ${formatDateTime(r.validatedAt)}`)
  lines.push(t.disclaimer)
  return lines.join('\n')
}
